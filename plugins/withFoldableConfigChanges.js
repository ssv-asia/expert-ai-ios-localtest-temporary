// Fixes the root cause of "chat and in-flight response disappear when the
// screen changes on a foldable" — MainActivity's android:configChanges was
// missing `smallestScreenSize` and `density`. Those are exactly the
// configuration categories that change when a Samsung Fold (or similar)
// folds/unfolds: without them listed, Android's default behavior is to
// DESTROY AND RECREATE the whole Activity — including the JS engine and all
// in-memory React state — instead of just letting the app resize in place.
// The existing 1.5s streaming checkpoint (see app/simple-chat.tsx) was a
// mitigation for the data-loss symptom of this; this is the actual fix for
// the cause.
//
// android/ is gitignored and regenerated by `expo prebuild` on every EAS
// build, so this has to be a plugin that reapplies the attribute every time,
// not a one-off manual edit to AndroidManifest.xml.
const { withAndroidManifest } = require('@expo/config-plugins');

const REQUIRED_CONFIG_CHANGES = [
  'keyboard',
  'keyboardHidden',
  'orientation',
  'screenSize',
  'screenLayout',
  'smallestScreenSize',
  'density',
  'uiMode',
];

module.exports = function withFoldableConfigChanges(config) {
  return withAndroidManifest(config, (config) => {
    const application = config.modResults.manifest.application?.[0];
    const activities = application?.activity ?? [];
    const mainActivity = activities.find((a) => a.$?.['android:name'] === '.MainActivity');
    if (!mainActivity) return config;

    const existing = (mainActivity.$['android:configChanges'] ?? '')
      .split('|')
      .map((s) => s.trim())
      .filter(Boolean);
    const merged = Array.from(new Set([...existing, ...REQUIRED_CONFIG_CHANGES]));
    mainActivity.$['android:configChanges'] = merged.join('|');

    return config;
  });
};
